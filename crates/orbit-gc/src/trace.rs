//! How objects and roots tell the collector what they point to.

use crate::arena::{AnyGc, Gc, Gen, Store};
use std::collections::hash_map::Entry;
use std::collections::{BTreeSet, HashMap};
use std::fmt;
use std::hash::{BuildHasherDefault, Hasher};
use std::marker::PhantomData;

pub(crate) const WHITE: u8 = 0;
pub(crate) const GRAY: u8 = 1;
pub(crate) const BLACK: u8 = 2;
/// The slot holds no object. Never combined with other bits.
pub(crate) const FREE: u8 = 3;
pub(crate) const COLOR: u8 = 3;
/// Registered for finalization (in `finalizable` or `finalize_queue`).
pub(crate) const FIN: u8 = 4;
/// Unmarked, with ephemeron values in `Marks::waiting` for it to be marked.
pub(crate) const WAIT: u8 = 8;

/// A set of typed arenas, one per object type. Generated by
/// [`space!`](crate::space); not meant to be implemented by hand.
///
/// The methods take a kind number and a slot and dispatch to the arena of that
/// kind. The collector only calls them on occupied slots.
pub trait Space: Sized {
    /// How many arenas (object types) the space has.
    const KINDS: usize;
    /// Slots per page in every arena of the space.
    const PAGE_SLOTS: usize;

    #[doc(hidden)]
    fn trace_slot(&self, kind: u8, index: u32, m: &mut Marker<'_, Self>) -> usize;
    #[doc(hidden)]
    fn clear_slot(&mut self, kind: u8, index: u32, mode: WeakMode, live: &Liveness<'_, Self>);
    #[doc(hidden)]
    fn free_slot(&mut self, kind: u8, index: u32) -> usize;
    #[doc(hidden)]
    fn slot_bytes(kind: u8) -> usize;
    #[doc(hidden)]
    fn release_page(&mut self, kind: u8, page: u32);

    /// The Rust type stored in arena `kind`, for diagnostics.
    fn kind_name(kind: u8) -> &'static str;
}

/// A [`Space`] with an arena for `T`. Generated by [`space!`](crate::space).
pub trait Holds<T>: Space {
    /// The arena's kind number: its position in the `space!` declaration.
    const KIND: u8;
    #[doc(hidden)]
    type Arena: Store<T>;
    #[doc(hidden)]
    fn arena(&self) -> &Self::Arena;
    #[doc(hidden)]
    fn arena_mut(&mut self) -> &mut Self::Arena;
}

/// An object the collector manages in space `S`.
///
/// `trace` must report every handle the object holds strongly, by calling
/// [`Marker::mark`] on it. A handle it forgets can be collected while still in
/// use, which later panics or reads the wrong object.
pub trait Trace<S: Space>: Sized {
    /// Objects that hold no handles (strings, for example) can set this so
    /// they are marked black at once and never queued for tracing.
    const LEAF: bool = false;

    /// Report the handles this object holds.
    fn trace(&self, m: &mut Marker<'_, S>);

    /// Bytes this object owns outside its arena slot (a `Vec`'s buffer, a
    /// string's bytes), for pacing and [`Heap::bytes`](crate::Heap::bytes).
    ///
    /// It is read when the object is allocated and when it is freed. When it
    /// changes in between, report the difference: [`Heap::update`](crate::Heap::update)
    /// does that for you, or call [`Heap::adjust_bytes`](crate::Heap::adjust_bytes).
    fn extra_bytes(&self) -> usize {
        0
    }

    /// Drop entries whose weak references died. Called only on objects that
    /// called [`Marker::weak`] while being traced in this cycle.
    ///
    /// Remove an entry when `mode.keys` is set and its weak key is dead, or
    /// when `mode.values` is set and its weak value is dead. Ask
    /// [`Liveness::is_live`] which handles are still alive.
    fn clear_weak(&mut self, mode: WeakMode, live: &Liveness<'_, S>) {
        let _ = (mode, live);
    }
}

/// Which references in an object are weak.
///
/// - `keys` only: an ephemeron table. A value is kept alive only while its key
///   is: report each entry with [`Marker::ephemeron`].
/// - `values` only: a weak-value table.
/// - both: a table where every reference is weak.
///
/// Entries whose weak *values* die are removed before finalizers are queued,
/// so a weak value never exposes an object that is about to be finalized.
/// Entries whose weak *keys* die are removed after, so an entry keyed by an
/// object being finalized survives until the next cycle, as in Lua.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub struct WeakMode {
    pub keys: bool,
    pub values: bool,
}

impl WeakMode {
    pub const KEYS: WeakMode = WeakMode {
        keys: true,
        values: false,
    };
    pub const VALUES: WeakMode = WeakMode {
        keys: false,
        values: true,
    };
    pub const BOTH: WeakMode = WeakMode {
        keys: true,
        values: true,
    };
}

/// The roots the collector marks from: everything the mutator can reach
/// without going through the heap (the VM stack, open upvalues, globals, the
/// registry, handles a Rust function holds across a collection).
///
/// Any closure `Fn(&mut Marker<S>)` is a `Roots`, and so is `()` (no roots).
pub trait Roots<S: Space> {
    /// Mark every root.
    fn trace(&self, m: &mut Marker<'_, S>);

    /// Drop weak references held outside the heap, such as a string intern
    /// table. Called once per cycle after all marking, before the sweep.
    fn clear_weak(&mut self, live: &Liveness<'_, S>) {
        let _ = live;
    }
}

impl<S: Space, F: Fn(&mut Marker<'_, S>)> Roots<S> for F {
    fn trace(&self, m: &mut Marker<'_, S>) {
        self(m)
    }
}

impl<S: Space> Roots<S> for () {
    fn trace(&self, _: &mut Marker<'_, S>) {}
}

/// Collector state for one page of an arena.
#[derive(Debug, Default)]
pub(crate) struct PageMeta {
    /// Slots freed by the sweep, as in-page offsets.
    pub(crate) free: Vec<u16>,
    /// Slots from here to the end of the page have never been used. Zero
    /// while the page is released.
    pub(crate) fresh: u32,
    /// Occupied slots.
    pub(crate) live: u32,
    /// Whether the page's memory is allocated.
    pub(crate) allocated: bool,
    /// Listed in `KindMeta::open`.
    pub(crate) open: bool,
}

/// Per-arena collector state.
#[derive(Debug)]
pub(crate) struct KindMeta {
    pub(crate) shift: u32,
    /// One byte per slot: a color, or `FREE`, plus the `FIN` bit. Flat, for
    /// fast marking; it covers pages up to the last allocated one, and is cut
    /// back when the pages at the end are released.
    pub(crate) color: Vec<u8>,
    pub(crate) pages: Vec<PageMeta>,
    /// Allocated pages with a free slot. New objects go into the lowest, so
    /// objects pack into low pages and high pages drain and get released.
    pub(crate) open: BTreeSet<u32>,
    /// `open`'s first element, cached for the allocation fast path.
    pub(crate) cur: Option<u32>,
    /// Released pages below `pages.len()`, so allocation finds the lowest
    /// without scanning every page.
    pub(crate) released: BTreeSet<u32>,
    /// Occupied slots in the whole arena.
    pub(crate) live: usize,
    /// Pages currently allocated.
    pub(crate) allocated: usize,
}

impl KindMeta {
    pub(crate) fn new(shift: u32) -> Self {
        KindMeta {
            shift,
            color: Vec::new(),
            pages: Vec::new(),
            open: BTreeSet::new(),
            cur: None,
            released: BTreeSet::new(),
            live: 0,
            allocated: 0,
        }
    }

    #[inline(always)]
    pub(crate) fn split(&self, i: u32) -> (usize, usize) {
        (
            (i >> self.shift) as usize,
            i as usize & ((1usize << self.shift) - 1),
        )
    }

    pub(crate) fn page_slots(&self) -> u32 {
        1 << self.shift
    }

    /// Pick a slot for a new object. Returns its index.
    #[inline]
    pub(crate) fn take_slot(&mut self) -> u32 {
        // The usual case: the current page has a free or fresh slot.
        if let Some(p) = self.cur {
            let n = self.page_slots();
            let page = &mut self.pages[p as usize];
            let offset = match page.free.pop() {
                Some(o) => Some(u32::from(o)),
                None if page.fresh < n => {
                    page.fresh += 1;
                    Some(page.fresh - 1)
                }
                None => None,
            };
            if let Some(o) = offset {
                page.live += 1;
                self.live += 1;
                return (p << self.shift) | o;
            }
        }
        self.take_slot_slow()
    }

    /// [`KindMeta::take_slot`] when the current page is full or there is
    /// none: move on to the next open page, or open one.
    #[cold]
    #[inline(never)]
    fn take_slot_slow(&mut self) -> u32 {
        let n = self.page_slots();
        while let Some(p) = self.cur {
            let page = &mut self.pages[p as usize];
            let offset = match page.free.pop() {
                Some(o) => Some(u32::from(o)),
                None if page.fresh < n => {
                    page.fresh += 1;
                    Some(page.fresh - 1)
                }
                None => None,
            };
            if let Some(o) = offset {
                page.live += 1;
                self.live += 1;
                return (p << self.shift) | o;
            }
            // Full: stop offering it.
            page.open = false;
            self.open.remove(&p);
            self.cur = self.open.first().copied();
        }
        // Every allocated page is full. Reuse the lowest released page, or
        // add one.
        let p = match self.released.pop_first() {
            Some(p) => p as usize,
            None => {
                self.pages.push(PageMeta::default());
                self.pages.len() - 1
            }
        };
        assert!(
            p <= (u32::MAX >> self.shift) as usize,
            "orbit-gc: arena full"
        );
        let end = (p + 1) << self.shift;
        if self.color.len() < end {
            self.color.resize(end, FREE);
        }
        let page = &mut self.pages[p];
        *page = PageMeta {
            free: Vec::new(),
            fresh: 1,
            live: 1,
            allocated: true,
            open: true,
        };
        self.allocated += 1;
        self.live += 1;
        let p = p as u32;
        self.open.insert(p);
        self.cur = self.open.first().copied();
        p << self.shift
    }

    /// Return slot `i` to its page's free list.
    #[inline]
    pub(crate) fn free_slot(&mut self, i: u32) {
        self.color[i as usize] = FREE;
        let (p, o) = self.split(i);
        let page = &mut self.pages[p];
        page.free.push(o as u16);
        page.live -= 1;
        self.live -= 1;
        if !page.open {
            self.reopen(p);
        }
    }

    /// Offer page `p` again: [`KindMeta::free_slot`] freed a slot in it
    /// after it had filled up.
    #[cold]
    #[inline(never)]
    fn reopen(&mut self, p: usize) {
        self.pages[p].open = true;
        self.open.insert(p as u32);
        if self.cur.is_none_or(|c| (p as u32) < c) {
            self.cur = Some(p as u32);
        }
    }

    /// Forget page `p`, which has no live objects. When it was the last
    /// allocated page, also drop the released pages at the end and their
    /// colors.
    pub(crate) fn release_page(&mut self, p: u32) {
        debug_assert_eq!(self.pages[p as usize].live, 0);
        self.pages[p as usize] = PageMeta::default();
        self.allocated -= 1;
        self.open.remove(&p);
        if self.cur == Some(p) {
            self.cur = self.open.first().copied();
        }
        if p as usize + 1 < self.pages.len() {
            self.released.insert(p);
            return;
        }
        // Each page dropped here was scanned once, so this is linear overall.
        let used = self.pages[..p as usize]
            .iter()
            .rposition(|pg| pg.allocated)
            .map_or(0, |q| q + 1);
        self.pages.truncate(used);
        self.released.split_off(&(used as u32));
        let len = used << self.shift;
        if len < self.color.len() {
            self.color.truncate(len);
            if self.color.capacity() > 2 * len.max(1 << self.shift) {
                self.color.shrink_to_fit();
            }
        }
    }
}

/// The ephemeron values waiting for one key. Most keys have one, so it is
/// stored inline; only a second value allocates.
#[derive(Debug)]
pub(crate) enum WaitList {
    One(AnyGc),
    Many(Vec<AnyGc>),
}

impl WaitList {
    fn push(&mut self, v: AnyGc) {
        match self {
            WaitList::One(a) => *self = WaitList::Many(vec![*a, v]),
            WaitList::Many(l) => l.push(v),
        }
    }

    fn drain_into(self, todo: &mut Vec<AnyGc>) {
        match self {
            WaitList::One(a) => todo.push(a),
            WaitList::Many(l) => todo.extend(l),
        }
    }
}

/// A multiply-rotate hasher for the wait map. Its keys are slot numbers the
/// collector chose, so they need no protection against chosen collisions,
/// and SipHash would cost half of marking an ephemeron table
/// (`docs/design/gc-spike-ephemerons.md`).
#[derive(Default, Clone, Copy)]
pub(crate) struct SlotHasher(u64);

impl Hasher for SlotHasher {
    #[inline]
    fn write(&mut self, bytes: &[u8]) {
        for &b in bytes {
            self.write_u64(u64::from(b));
        }
    }

    #[inline]
    fn write_u8(&mut self, i: u8) {
        self.write_u64(u64::from(i));
    }

    #[inline]
    fn write_u32(&mut self, i: u32) {
        self.write_u64(u64::from(i));
    }

    #[inline]
    fn write_u64(&mut self, i: u64) {
        self.0 = (self.0.rotate_left(5) ^ i).wrapping_mul(0x517c_c1b7_2722_0a95);
    }

    #[inline]
    fn finish(&self) -> u64 {
        self.0
    }
}

/// Ephemeron values by the slot of the unmarked key they wait on.
pub(crate) type WaitMap = HashMap<(u8, u32), WaitList, BuildHasherDefault<SlotHasher>>;

/// The collector state marking needs.
#[derive(Debug)]
pub(crate) struct Marks {
    pub(crate) meta: Vec<KindMeta>,
    pub(crate) gray: Vec<AnyGc>,
    /// Ephemeron values by the unmarked key that keeps them alive. Marking a
    /// key marks its values, so ephemerons need no rescans; entries left at
    /// the end of marking belong to dead keys.
    pub(crate) waiting: WaitMap,
    /// Reused work list for [`Marks::release`].
    pub(crate) scratch: Vec<AnyGc>,
    /// Bytes of the objects marked so far in this cycle: at the end of
    /// marking, the reachable heap.
    pub(crate) marked_bytes: usize,
}

impl Marks {
    /// Mark an object. Returns true if it was unmarked.
    #[inline(always)]
    pub(crate) fn mark_raw(&mut self, kind: u8, index: u32, leaf: bool) -> bool {
        let c = &mut self.meta[kind as usize].color[index as usize];
        debug_assert!(*c != FREE, "orbit-gc: marking a stale handle");
        if *c & COLOR != WHITE {
            return false;
        }
        let waited = *c & WAIT != 0;
        if leaf {
            *c = (*c & !(COLOR | WAIT)) | BLACK;
        } else {
            *c = (*c & !(COLOR | WAIT)) | GRAY;
            self.gray.push(AnyGc {
                kind,
                index,
                generation: Gen::default(),
            });
        }
        if waited {
            self.release(kind, index);
        }
        true
    }

    /// Mark the ephemeron values that were waiting for this key, and any
    /// waiting for those in turn. A loop rather than recursion, so a long
    /// chain of ephemerons can't overflow the stack.
    #[cold]
    fn release(&mut self, kind: u8, index: u32) {
        let Some(first) = self.waiting.remove(&(kind, index)) else {
            return;
        };
        let mut todo = std::mem::take(&mut self.scratch);
        first.drain_into(&mut todo);
        while let Some(v) = todo.pop() {
            let c = &mut self.meta[v.kind as usize].color[v.index as usize];
            debug_assert!(*c != FREE, "orbit-gc: marking a stale handle");
            if *c & COLOR != WHITE {
                continue;
            }
            let waited = *c & WAIT != 0;
            *c = (*c & !(COLOR | WAIT)) | GRAY;
            self.gray.push(v);
            if waited && let Some(more) = self.waiting.remove(&(v.kind, v.index)) {
                more.drain_into(&mut todo);
            }
        }
        self.scratch = todo;
    }

    /// Keep `value` alive if `key` is, now or once it is marked.
    fn ephemeron(&mut self, key: AnyGc, value: AnyGc) {
        if self.is_marked(key.kind, key.index) {
            self.mark_raw(value.kind, value.index, false);
        } else if !self.is_marked(value.kind, value.index) {
            self.meta[key.kind as usize].color[key.index as usize] |= WAIT;
            match self.waiting.entry((key.kind, key.index)) {
                Entry::Vacant(e) => {
                    e.insert(WaitList::One(value));
                }
                Entry::Occupied(mut e) => e.get_mut().push(value),
            }
        }
    }

    /// Forget the ephemeron values still waiting: their keys are dead.
    pub(crate) fn clear_waiting(&mut self) {
        for &(kind, index) in self.waiting.keys() {
            self.meta[kind as usize].color[index as usize] &= !WAIT;
        }
        self.waiting.clear();
        if self.waiting.capacity() > 1024 {
            self.waiting.shrink_to_fit();
        }
    }

    #[inline]
    pub(crate) fn is_marked(&self, kind: u8, index: u32) -> bool {
        let c = self.meta[kind as usize].color[index as usize];
        debug_assert!(c != FREE, "orbit-gc: liveness of a stale handle");
        c & COLOR != WHITE
    }
}

/// Passed to [`Trace::trace`] and [`Roots::trace`] to mark what they reach.
pub struct Marker<'a, S: Space> {
    pub(crate) space: &'a S,
    pub(crate) marks: &'a mut Marks,
    /// Set by `weak` while tracing a heap object, if registration is on.
    pub(crate) weak: Option<WeakMode>,
    pub(crate) can_register: bool,
}

impl<S: Space> fmt::Debug for Marker<'_, S> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Marker").finish_non_exhaustive()
    }
}

impl<'a, S: Space> Marker<'a, S> {
    /// Mark `gc` reachable.
    #[inline]
    pub fn mark<T: Trace<S>>(&mut self, gc: Gc<T>)
    where
        S: Holds<T>,
    {
        let kind = <S as Holds<T>>::KIND;
        if self.marks.mark_raw(kind, gc.index(), T::LEAF) && T::LEAF {
            // Leaves are never traced, so count their bytes here.
            let obj = self.space.arena().get(gc);
            self.marks.marked_bytes += crate::heap::slot_size::<T>() + obj.extra_bytes();
        }
    }

    /// Mark an untyped handle reachable.
    pub fn mark_any(&mut self, gc: AnyGc) {
        self.marks.mark_raw(gc.kind, gc.index, false);
    }

    /// Report an ephemeron entry: `value` stays alive as long as `key` does,
    /// and `key` is not kept alive by the entry. Call it for every entry of
    /// an object that declares [`WeakMode::KEYS`]. If the key is not marked
    /// yet, the value is marked when (and if) the key is.
    ///
    /// A key that can't be collected (a number, or a string if strings count
    /// as values) should not be reported: mark the value directly.
    pub fn ephemeron(&mut self, key: AnyGc, value: AnyGc) {
        self.marks.ephemeron(key, value);
    }

    /// Erase a handle's type, for [`Marker::ephemeron`].
    #[inline]
    pub fn erase<T>(&self, gc: Gc<T>) -> AnyGc
    where
        S: Holds<T>,
    {
        AnyGc {
            kind: <S as Holds<T>>::KIND,
            index: gc.index(),
            generation: Gen::new(gc.generation()),
        }
    }

    /// Read another object while tracing, such as a table's metatable to find
    /// its weak mode.
    #[inline]
    #[track_caller]
    pub fn get<T>(&self, gc: Gc<T>) -> &'a T
    where
        S: Holds<T>,
    {
        self.space.arena().get(gc)
    }

    /// Declare that the object being traced holds weak references, so the
    /// collector calls its [`Trace::clear_weak`] at the end of the cycle.
    /// Call it on every trace; the declaration lasts one cycle. Ignored when
    /// tracing roots.
    pub fn weak(&mut self, mode: WeakMode) {
        if self.can_register {
            self.weak = Some(mode);
        }
    }
}

/// Passed to [`Trace::clear_weak`] and [`Roots::clear_weak`]: which objects
/// survived marking.
pub struct Liveness<'a, S: Space> {
    pub(crate) marks: &'a Marks,
    pub(crate) _s: PhantomData<fn() -> S>,
}

impl<S: Space> fmt::Debug for Liveness<'_, S> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Liveness").finish_non_exhaustive()
    }
}

impl<S: Space> Liveness<'_, S> {
    /// Whether `gc` survives this cycle.
    #[inline]
    pub fn is_live<T>(&self, gc: Gc<T>) -> bool
    where
        S: Holds<T>,
    {
        self.marks.is_marked(<S as Holds<T>>::KIND, gc.index())
    }
}
