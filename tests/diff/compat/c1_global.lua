-- Lua 5.5 global declarations: compile errors, const globals, initialisation.
local function c(src)
  local f, e = load(src, "=decl")
  if f then print("ok") else print(e) end
end
c("global x; y = 1")
c("global x; x = 1; return x")
c("do global x end y = 1")
c("global<const> x; x = 1")
c("global x<const>, y; y = 1; x = 2")
c("global<const> *; print(x)")
c("global<const> *; x = 1")
c("global x; global<const> *; x = 1; y = 2")
c("global *; do global<const> * x = 1 end")
c("global x <const>; global *; x = 1")
c("local x; do global<const> * x = 1 end")
c("global<close> x")
c("global x<foo>")
c("global x; local function f() return function() y = 1 end end")
c("global x; function f:m() end")
c("global x; function x.y() end")
c("global _ENV; local q = _ENV")
c("global none; return 1 + 2")
local function r(src)
  local f, e = load(src, "=run")
  if not f then print("compile:", e) return end
  print(pcall(f))
end
r("global a1 = 1; return a1")
r("a2 = 5; global a2 = 1; return a2")
r("a3 = false; global a3 = 1")
r("a5 = 3; global a4, a5 = 1, 2; return a4, a5")
print(a4, a5)
r("global a6, a7 = 1; return a6, a7")
r("global function gf() return 'gf' end return gf()")
r("global function gf() return 'again' end")
r("global<const> a8 = 8; return a8")
r("local _ENV = {}; global a9 = 9; return a9")
