-- Finalizer errors become warnings, shown only while warnings are on.
warn("@on")
setmetatable({}, {__gc = function() error("boom") end})
collectgarbage()
setmetatable({}, {__gc = function() error({}) end})
collectgarbage()
setmetatable({}, {__gc = function() error() end})
collectgarbage()
setmetatable({}, {__gc = 1})
collectgarbage()
print("end")
warn("@off")
setmetatable({}, {__gc = function() error("quiet") end})
collectgarbage()
print("done")
