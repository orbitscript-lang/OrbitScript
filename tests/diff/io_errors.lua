-- Failed file operations return the system's errno and its strerror text,
-- including failures the library detects before asking the system.
local name = os.tmpname()
local f = assert(io.open(name, "w"))
print(f:seek("set", -1))
print(f:seek("cur", -1))
print(f:seek("end", -100))
print(f:setvbuf("full", -1) == f)
f:close()
print(pcall(f.seek, f))
print(io.open("/nonexistent-dir/x"))
print(io.open("/nonexistent-dir/x", "w"))
print(io.open("/", "w"))
local r = assert(io.open(name, "r"))
print(r:write("x"))
r:close()
print(os.rename("/nonexistent-dir/a", "/nonexistent-dir/b"))
print(os.remove("/nonexistent-dir/a"))
print(io.lines(name)())
os.remove(name)
local ok, msg = pcall(io.lines, name)
print(ok, (msg:gsub(name:gsub("%p", "%%%0"), "NAME")))
