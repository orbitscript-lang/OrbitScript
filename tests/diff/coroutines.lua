-- Coroutines: resume/yield, wrap, status, errors, close.
local co = coroutine.create(function (a, b)
  print("start", a, b)
  local c = coroutine.yield(a + b)
  print("got", c)
  local d, e = coroutine.yield(c * 2)
  return d + e
end)
print(coroutine.resume(co, 1, 2))
print(coroutine.status(co), coroutine.resume(co, 10))
print(coroutine.resume(co, 3, 4))
print(coroutine.status(co), coroutine.resume(co))
local gen = coroutine.wrap(function () for i = 1, 3 do coroutine.yield(i) end end)
print(gen(), gen(), gen())
local bad = coroutine.create(function () error("oops") end)
print(coroutine.resume(bad))
local bad2 = coroutine.create(function () error({code = 7}) end)
local ok, e = coroutine.resume(bad2)
print(ok, type(e), e.code)
print(coroutine.isyieldable(), coroutine.running())
local c2 = coroutine.create(function () local x <close> = setmetatable({}, {__close = function () print("closing") end}); coroutine.yield() end)
coroutine.resume(c2)
print(coroutine.close(c2), coroutine.status(c2))

-- create, status, running and isyieldable: argument checks and results.
do
  print(pcall(coroutine.create))
  print(pcall(coroutine.create, 1))
  print(type(coroutine.create(print)), coroutine.status(coroutine.create(print)))
  print(pcall(coroutine.status))
  print(pcall(coroutine.status, {}))
  local t, m = coroutine.running() print(type(t), m)
  print(coroutine.isyieldable())
  print(pcall(coroutine.isyieldable, nil))
  print(pcall(coroutine.isyieldable, 1))
  local co = coroutine.create(function()
    local t2, m2 = coroutine.running()
    print(type(t2), m2, coroutine.status(t2), coroutine.isyieldable(), coroutine.isyieldable(t))
    coroutine.yield()
  end)
  coroutine.resume(co)
  print(coroutine.status(co), coroutine.isyieldable(co))
  coroutine.resume(co)
  print(coroutine.status(co))
  print(select("#", coroutine.running()))
  local wrapcreate = coroutine.wrap(function() return coroutine.status(coroutine.running()) end)
  print(wrapcreate())
  print(coroutine.status(coroutine.create(coroutine.create)))
end
