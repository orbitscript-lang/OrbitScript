-- Coroutines: resume/yield, wrap, status, errors, close.
local co = coroutine.create(function (a, b)
  print("start", a, b)
  local c = coroutine.yield(a + b)
  print("got", c)
  local d, e = coroutine.yield(c * 2)
  return d + e
end)
print(coroutine.resume(co, 1, 2))
print(coroutine.status(co), coroutine.resume(co, 10))
print(coroutine.resume(co, 3, 4))
print(coroutine.status(co), coroutine.resume(co))
local gen = coroutine.wrap(function () for i = 1, 3 do coroutine.yield(i) end end)
print(gen(), gen(), gen())
local bad = coroutine.create(function () error("oops") end)
print(coroutine.resume(bad))
local bad2 = coroutine.create(function () error({code = 7}) end)
local ok, e = coroutine.resume(bad2)
print(ok, type(e), e.code)
print(coroutine.isyieldable(), coroutine.running())
local c2 = coroutine.create(function () local x <close> = setmetatable({}, {__close = function () print("closing") end}); coroutine.yield() end)
coroutine.resume(c2)
print(coroutine.close(c2), coroutine.status(c2))
