-- First-light subset: error, pcall, assert, runtime error messages.
print(pcall(error, "plain"))
print(pcall(function() error("with position") end))
print(pcall(function() error("no position", 0) end))
local function blame_caller() error("caller's fault", 2) end
print(pcall(function() blame_caller() end))
print(pcall(error, {code = 7}))
print(select("#", pcall(error)))
print(pcall(function() local t = nil; return t.x end))
print(pcall(function() return missing.field end))
print(pcall(function() local t = {}; return t.a.b end))
print(pcall(function() missing_fn() end))
print(pcall(function() local o = {}; o:nomethod() end))
print(pcall(function() return 1 + {} end))
print(pcall(function() local s = "x"; return s + 1 end))
print(pcall(function() return 1 < "2" end))
print(pcall(function() return {} .. "" end))
print(pcall(function() return #nil end))
print(pcall(function() return 1 // 0 end))
print(pcall(function() local t = {}; t[nil] = 1 end))
print(pcall(function() for k = 1, 2, 0 do end end))
print(pcall(assert, false))
print(pcall(assert, nil, "custom assert"))
print(assert(1, "unused"))
print(pcall(function() local function r() return 1 + r() end; return r() end))
local ok, e = pcall(pcall)
print(ok, e)
print(pcall(pcall, error, "nested"))
